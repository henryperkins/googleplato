import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, symlinkSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import Database from 'better-sqlite3';

const root = new URL('../../', import.meta.url);
test('export and apply contain even malicious legacy lesson IDs and manifest filenames', t => {
  const dir = mkdtempSync(join(tmpdir(), 'plato-export-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const dbPath = join(dir, 'test.db');
  const out = join(dir, 'out');
  const env = { ...process.env, DB_BACKEND: 'sqlite', SQLITE_PATH: dbPath };
  const run = (script, ...args) => spawnSync(process.execPath, [script, ...args], { cwd: root, env, encoding: 'utf8' });
  const initialized = spawnSync(process.execPath, ['--input-type=module', '-e', "await import('./src/lib/db-sqlite.js')"], { cwd: root, env, encoding: 'utf8' });
  assert.equal(initialized.status, 0, initialized.stderr);
  const sql = new Database(dbPath);
  const markdown = '# Safe\n\n## Learning Objectives\n- Can explain one\n- Can explain two\n';
  sql.prepare('INSERT INTO sync_data (userId,dataKey,data,version,updatedAt) VALUES (?,?,?,?,?)').run('_system', 'lesson:../AGENTS', JSON.stringify({ name: 'Legacy', markdown, status: 'private' }), 1, new Date().toISOString());
  sql.close();
  const sentinel = join(dir, 'AGENTS.md');
  writeFileSync(sentinel, 'protected');
  const exported = run('scripts/export-lessons.js', out);
  assert.equal(exported.status, 0, exported.stderr);
  assert.equal(readFileSync(sentinel, 'utf8'), 'protected');
  const manifest = JSON.parse(readFileSync(join(out, 'manifest.json'), 'utf8'));
  assert.equal(manifest.lessons[0].lessonId, '../AGENTS');
  assert.match(manifest.lessons[0].file, /^lesson-[a-f0-9]{64}\.md$/);
  assert.equal(readFileSync(join(out, manifest.lessons[0].file), 'utf8'), markdown);
  manifest.lessons[0].file = '../AGENTS.md';
  writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest));
  const applied = run('scripts/apply-lessons.js', out, '--apply');
  assert.notEqual(applied.status, 0, 'unsafe manifest reads are refused');
  manifest.lessons[0].file = 'linked.md';
  writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest));
  symlinkSync(sentinel, join(out, 'linked.md'));
  assert.notEqual(run('scripts/apply-lessons.js', out).status, 0, 'symlink escapes are refused');
});
